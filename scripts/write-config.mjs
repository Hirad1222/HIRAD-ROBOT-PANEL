// Generates the public frontend config from a WORKER_URL value. Usage: node scripts/write-config.mjs <url> <outfile>
import { writeFileSync } from 'node:fs';
export function configSource(url) {
  const u = String(url ?? '').trim().replace(/\/+$/, '');
  if (!/^https:\/\/[A-Za-z0-9.-]+(:\d+)?$/.test(u)) throw new Error('WORKER_URL must be an https:// origin without a path, e.g. https://name.account.workers.dev');
  return `// Generated by the deploy workflow. Public and non-secret.\nwindow.HIRAD_CONFIG = { API_BASE_URL: ${JSON.stringify(u)} };\n`;
}
if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file:').href) {
  try { writeFileSync(process.argv[3], configSource(process.argv[2])); console.log('config written'); }
  catch (e) { console.error('::error::' + e.message); process.exit(1); }
}
